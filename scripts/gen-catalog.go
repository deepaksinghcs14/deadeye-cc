//go:build ignore

// gen-catalog regenerates internal/catalog/catalog_gen.go from the price
// seed table below, ranked by blended price (input + 4*output, a rough
// usage-mix weight per PLAN.md §4). Run after editing seed prices, or once
// per release to pick up new models:
//
//	go run scripts/gen-catalog.go
//
// There is no reachable pricing API from the Claude Code hook environment
// (docs/verified.md V7), so the seed table below is maintained by hand
// against https://platform.claude.com/docs/en/about-claude/pricing.
package main

import (
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strings"
)

type seedModel struct {
	id, family              string
	inputPrice, outputPrice float64
	role                    string // "" | "unsure_ceiling" | "high_ceiling" -- see catalog.Role*
}

// Seed prices, USD per million tokens. Update these, not catalog_gen.go.
//
// role marks which model the kernel's two ceilings resolve to (see
// catalog.Catalog.UnsureCeiling/HighCeiling) -- exactly one model should
// carry "unsure_ceiling" and one "high_ceiling"
// (TestBuiltinHasExactlyOneOfEachCeilingRole guards this). fable stays
// un-roled deliberately: it's not reachable by automatic routing, on
// purpose, the same real-world outcome as before Role existed -- now an
// explicit choice here instead of an emergent side effect of a tier
// number hardcoded in kernel.go.
var seed = []seedModel{
	// deadeye: haiku priced at its base rate only. ceiling: prompts over 100k tokens bill 5x ($0.50/$2.50), so savings on large-context haiku calls are overstated. upgrade: when the catalog carries more than one price per model.
	{"claude-haiku-5-5", "haiku", 0.1, 0.5, ""},
	{"claude-sonnet-5-5", "sonnet", 2, 10, "unsure_ceiling"},
	{"claude-opus-5-5", "opus", 4, 20, "high_ceiling"},
	{"claude-fable-5-1", "fable", 10, 50, ""},
}

const builtAt = "2026-10-11" // date the seed prices above were fetched
const sourceURL = "https://platform.claude.com/docs/en/about-claude/pricing"

// hostSeed is one non-Claude host's price table. Each host gets its own
// catalog because a model id only means something to the host that runs
// it: Codex routing must hand spawn_agent a Codex slug, never a Claude
// one. family is the short label deadeye prints; these hosts take the full
// id, so nothing depends on it the way Claude's Agent tool does.
type hostSeed struct {
	host, sourceURL string
	models          []seedModel
}

var hostSeeds = []hostSeed{
	// Codex is the one non-Claude host with a routing consumer: a
	// PreToolUse hook can rewrite spawn_agent's model. gpt-6-sol is left out
	// -- same price as gpt-6.1-sol, which the models page recommends.
	{"codex", "https://developers.openai.com/api/docs/pricing", []seedModel{
		{"gpt-6-luna", "luna", 0.1, 0.5, ""},
		{"gpt-6.1-sol", "sol", 2, 10, "unsure_ceiling"},
		{"gpt-6-astra", "astra", 10, 50, "high_ceiling"},
	}},
	// Gemini CLI and Cursor: display and stats only. Neither host lets a hook
	// change a subagent's model, so nothing routes on these yet.
	//
	// deadeye: gemini-3.8-flash at its introductory price. ceiling: it doubles to $1.50/$7.50 on 2027-01-01. upgrade: re-seed before that date.
	// deadeye: gemini-3.1-pro-preview at its under-200k-token price. ceiling: longer prompts bill $4/$18. upgrade: when the catalog carries more than one price per model.
	{"gemini", "https://ai.google.dev/gemini-api/docs/pricing", []seedModel{
		{"gemini-3.5-flash-lite", "flash-lite", 0.3, 2.5, ""},
		{"gemini-3.8-flash", "flash", 0.75, 3.75, "unsure_ceiling"},
		{"gemini-3.1-pro-preview", "pro", 2, 12, "high_ceiling"},
	}},
	// Cursor's own models only -- it also resells every other vendor's. The
	// ids are the display names from Cursor's pricing page, which gives no
	// slugs for them. No ceiling roles: two models don't make a three-way
	// ladder, and nothing routes on this catalog.
	{"cursor", "https://cursor.com/docs/models", []seedModel{
		{"Composer 2.5", "composer", 0.5, 2.5, ""},
		{"Grok 4.7", "grok", 2, 6, ""},
	}},
}

func blended(m seedModel) float64 { return m.inputPrice + 4*m.outputPrice }

func rank(models []seedModel) []seedModel {
	ranked := append([]seedModel(nil), models...)
	sort.SliceStable(ranked, func(i, j int) bool { return blended(ranked[i]) < blended(ranked[j]) })
	return ranked
}

func writeModels(b *strings.Builder, indent string, ranked []seedModel) {
	for tier, m := range ranked {
		fmt.Fprintf(b, "%s{ID: %q, Family: %q, InputPrice: %v, OutputPrice: %v, Tier: %d", indent, m.id, m.family, m.inputPrice, m.outputPrice, tier)
		if m.role != "" {
			fmt.Fprintf(b, ", Role: %q", m.role)
		}
		b.WriteString("},\n")
	}
}

func main() {
	ranked := rank(seed)

	var b strings.Builder
	fmt.Fprintf(&b, `// Code generated by scripts/gen-catalog.go from a manually-maintained price
// seed table; DO NOT EDIT directly -- edit the seed in the generator and
// re-run `+"`go run ./scripts/gen-catalog.go`"+`.
//
// Prices sourced from %s,
// fetched %s. No reachable pricing API exists in the Claude Code
// hook environment (docs/verified.md V7), so this table has no automated
// refresh; ~/.deadeye/catalog.json overrides it entirely if present.
package catalog

var builtin = Catalog{
	BuiltAt: %q,
	Source:  "builtin",
	Models: []Model{
`, sourceURL, builtAt, builtAt)
	writeModels(&b, "\t\t", ranked)
	b.WriteString("\t},\n}\n\n")

	b.WriteString("// builtinByHost holds the compiled-in catalog of every non-Claude host,\n// keyed by the --host value its hook adapter passes.\nvar builtinByHost = map[string]Catalog{\n")
	for _, h := range hostSeeds {
		fmt.Fprintf(&b, "\t// Prices sourced from %s.\n\t%q: {\n\t\tBuiltAt: %q,\n\t\tSource:  \"builtin\",\n\t\tModels: []Model{\n", h.sourceURL, h.host, builtAt)
		writeModels(&b, "\t\t\t", rank(h.models))
		b.WriteString("\t\t},\n\t},\n")
	}
	b.WriteString("}\n")

	out, err := format.Source([]byte(b.String()))
	if err != nil {
		fmt.Fprintln(os.Stderr, "gen-catalog: format:", err)
		os.Exit(1)
	}
	if err := os.WriteFile("internal/catalog/catalog_gen.go", out, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "gen-catalog: write:", err)
		os.Exit(1)
	}
	fmt.Println("wrote internal/catalog/catalog_gen.go")

	hosted := []struct {
		file   string
		models []seedModel
	}{{"docs/site/catalog.json", ranked}}
	for _, h := range hostSeeds {
		hosted = append(hosted, struct {
			file   string
			models []seedModel
		}{"docs/site/catalog-" + h.host + ".json", rank(h.models)})
	}
	for _, h := range hosted {
		if err := writeHostedCatalog(h.file, h.models); err != nil {
			fmt.Fprintln(os.Stderr, "gen-catalog: hosted json:", err)
			os.Exit(1)
		}
		fmt.Println("wrote " + h.file)
	}
}

// hostedModel/hostedCatalog mirror internal/catalog.Model/Catalog's JSON
// shape exactly (kept as a local copy, not an import, since this file is
// //go:build ignore and runs outside the module's normal build).
type hostedModel struct {
	ID          string  `json:"model_id"`
	Family      string  `json:"family"`
	InputPrice  float64 `json:"input_price"`
	OutputPrice float64 `json:"output_price"`
	Tier        int     `json:"tier"`
	Role        string  `json:"role,omitempty"`
}

type hostedCatalog struct {
	Models  []hostedModel `json:"models"`
	BuiltAt string        `json:"built_at"`
	Source  string        `json:"source"`
}

// writeHostedCatalog publishes one docs/site/catalog*.json -- the files
// cmd/deadeye/catalogcheck.go's background refresh fetches from GitHub
// Pages. Pretty-printed deliberately: these are meant to be hand-edited
// directly for a fast model/price change (edit, commit, push -- no
// release), so they should read like a table, not a minified blob. A hand
// edit here must be brought back into the seed above before the next
// `go run` clobbers it.
func writeHostedCatalog(file string, ranked []seedModel) error {
	hc := hostedCatalog{BuiltAt: builtAt, Source: "hosted"}
	for tier, m := range ranked {
		hc.Models = append(hc.Models, hostedModel{
			ID: m.id, Family: m.family, InputPrice: m.inputPrice, OutputPrice: m.outputPrice,
			Tier: tier, Role: m.role,
		})
	}
	b, err := json.MarshalIndent(hc, "", "  ")
	if err != nil {
		return err
	}
	return os.WriteFile(file, append(b, '\n'), 0o644)
}
